/**
 * くり上がりのあるたし算・くり下がりのあるひき算（1年）。
 *
 * ## なぜここを作るか
 *
 * **算数が苦手になる子の、いちばん下の段がここ。**
 * 8+5 や 13−8 が出てこないままだと、そのあとのひっ算・かけ算・わり算が
 * すべて「1けたの計算でつまずいて止まる」ことになる。
 * わり算のひっ算でいちばん引っかかるのが九九とひき算だ、というのは
 * このサイトの記録にも出ている。
 *
 * ## つまずきの本体
 *
 * 答えを覚えていないことではなく、**10のまとまりを作る手が出てこない**こと。
 *
 * - 8+5：8 に あと 2 で 10。だから 5 を 2 と 3 に分ける
 * - 13−8：13 を 10 と 3 に分ける。10 から 8 をひいて 2。2 と 3 で 5
 *
 * この「分ける」を紙に書くのが、さくらんぼ計算。
 * **書き方は知っていても、どちらの数を分けるのかで迷う**子が多い。
 * たし算では後ろの数を、ひき算では前の数を分ける。ここが逆になる。
 *
 * ## そこで、分ける数だけを問う
 *
 * 答えを先に聞かない。分ける数を1つずつ埋めさせて、
 * 最後に答えを打つ。どの段で止まったかが残る。
 */

export type SakuraKind =
  /** くり上がりのあるたし算（8 + 5） */
  | "add"
  /** くり下がりのあるひき算（13 − 8） */
  | "sub";

export type SakuraPlan = {
  id: string;
  kind: SakuraKind;
  /** 前の数 */
  a: number;
  /** 後ろの数 */
  b: number;
  answer: number;
  /**
   * さくらんぼの左のふさ。
   * たし算：10 にするために足りない数（8+5 なら 2）
   * ひき算：10 のまとまり（13−8 なら 10）
   */
  left: number;
  /**
   * さくらんぼの右のふさ。
   * たし算：分けたのこり（8+5 なら 3）
   * ひき算：一の位（13−8 なら 3）
   */
  right: number;
  /** ひき算で、10 から引いた答え（13−8 なら 2）。たし算では使わない */
  fromTen: number;
  stage: string;
};

/** どちらの数を分けるか。**たし算は後ろ、ひき算は前。** */
export const splitTarget = (plan: SakuraPlan): number =>
  plan.kind === "add" ? plan.b : plan.a;

/** 分けないほうの数。 */
export const keptNumber = (plan: SakuraPlan): number =>
  plan.kind === "add" ? plan.a : plan.b;

/** 「8 + 5」「13 − 8」 */
export const expression = (plan: SakuraPlan): string =>
  `${plan.a} ${plan.kind === "add" ? "+" : "−"} ${plan.b}`;

/** 10 のまとまりの中で、すでにうまっている数（たし算のとき）。 */
export const filledInTen = (plan: SakuraPlan): number => (plan.kind === "add" ? plan.a : 10);
